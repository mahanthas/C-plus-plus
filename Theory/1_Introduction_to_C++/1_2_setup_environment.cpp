/*
Setting Up Your Environment
Before writing any C++ code, you need:

A compiler to translate C++ code into machine code.
An editor/IDE for writing code.

Step 1: Install a C++ Compiler
    The most common compiler for C++ is GCC (GNU Compiler Collection), which works on all major platforms.

    Windows:
        Install MinGW. Or install MSYS2 and get GCC via pacman.
        Alternatively, you can use Microsoft Visual Studio which includes its own compiler.

Step 2: Choose a Text Editor or IDE
    You can write C++ code in a simple text editor or an IDE. Popular choices:

    Text Editors:
        Visual Studio Code: Lightweight and extensible.
        Vim or Emacs: Terminal-based editors for advanced users.
    IDEs:
        CLion: Full-featured C++ IDE (paid, with a free trial).
        Code::Blocks: Open-source C++ IDE.
        Eclipse CDT: Eclipse's C++ development tools.

Step 3: Verify the Compiler Installation
        Open your terminal or command prompt.
    Check the GCC version with:

    execute --> g++ --version

    If it outputs a version number, GCC is installed correctly.

*/